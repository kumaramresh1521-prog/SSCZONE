/**
 * SSCZONE Master Exam Syllabus Architecture
 * Comprehensive, notification-mapped chapters for SSC CGL, CHSL, CPO, MTS & GD.
 */

export interface ChapterItem {
  id: string;
  name: string;
  hindi_name: string;
  category: string; // e.g. "Arithmetic", "Advance Maths", "Verbal", "Polity", etc.
  high_weightage?: boolean;
  expected_questions?: string;
  notes_slug?: string; // Link to /blog/notes/[slug]
  practice_query: string; // Query for /speed-test?mode=topic&topicTitle=...
  default_tips?: string;
}

export interface SubjectCategory {
  id: "quant" | "reasoning" | "english" | "ga" | "computer";
  name: string;
  hindi_name: string;
  color: "blue" | "purple" | "emerald" | "amber" | "sky";
  icon: string;
  description: string;
  chapters: ChapterItem[];
}

export interface ExamSyllabus {
  exam_slug: "ssc-cgl" | "ssc-chsl" | "ssc-cpo" | "ssc-mts" | "ssc-gd";
  title: string;
  short_code: string;
  badge: string;
  tier_info: string;
  subjects: SubjectCategory[];
}

export interface UserChapterProgress {
  chapter_id: string;
  theory_done: boolean;
  practice_done: boolean;
  revision_count: number; // 0, 1, 2, 3+
  confidence: "low" | "medium" | "high" | "unrated";
  notes?: string;
  target_date?: string;
  updated_at: string;
}

export interface CustomTopicItem {
  id: string;
  subject_id: "quant" | "reasoning" | "english" | "ga" | "computer";
  name: string;
  category: string;
  created_at: string;
}

