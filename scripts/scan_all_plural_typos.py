detailed_paper_typos = {}

for p_item in papers_data:
    p = p_item["paper"]
    pid = p["id"]
    title = p["title"]
    qs = p_item["questions"]
    
    found_list = []
    
    for q in qs:
        qnum = q["question_number"]
        if qnum > 75: continue
        
        fields = ["question_text", "option_a", "option_b", "option_c", "option_d", "explanation"]
        for fn in fields:
            val = q.get(fn, "")
            if not val: continue
            
            for wrong, right in plural_stems:
                # check word boundary
                pattern = r'(?<![क-ह\u0900-\u097F])' + re.escape(wrong) + r'(?![क-ह\u0900-\u097F])'
                if re.search(pattern, val):
                    found_list.append({
                        "qnum": qnum,
                        "field": fn,
                        "wrong": wrong,
                        "correct": right,
                        "context": re.search(r'.{0,20}' + re.escape(wrong) + r'.{0,20}', val).group(0)
                    })
                    
    detailed_paper_typos[pid] = {
        "title": title,
        "count": len(found_list),
        "items": found_list
    }

for pid, d in detailed_paper_typos.items():
    print(f"\n=======================================================")
    print(f"Paper {pid:2d} ({d['title']}): {d['count']} typos found")
    for it in d["items"][:10]:
        print(f"  Q{it['qnum']} [{it['field']}]: '{it['wrong']}' -> '{it['correct']}' | Context: {it['context'].strip()}")
